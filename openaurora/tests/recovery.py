#!/usr/bin/env python3
"""Recovery integration tests. Fake display/watchdog/fallback; no TV or system power access."""
import os
from pathlib import Path
import signal
import subprocess
import tempfile
import time

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / os.environ.get("BUILD", "build")


def until(check, timeout=5):
    end = time.monotonic() + timeout
    while time.monotonic() < end:
        value = check()
        if value:
            return value
        time.sleep(0.025)
    raise AssertionError("deadline expired")


def read(path):
    try:
        return path.read_text()
    except FileNotFoundError:
        return ""


class Run:
    def __init__(self, directory, extra="", modules=True, wdt_fail=False):
        self.dir = directory
        self.hb = directory / "alive"
        self.ready = directory / "ready"
        self.stall = directory / "stall"
        self.events = directory / "events"
        self.fail = directory / "fail"
        self.enable = directory / "enable"
        self.safe = directory / "safe"
        self.config = directory / "config"
        self.config.write_text(f"host.heartbeat = {self.hb}\nui.ok_file = {self.ready}\n"
                               f"test.stall = {self.stall}\nui.dir = {directory}/no-icons\n" + extra)
        self.enable.touch()
        wdt, fallback = directory / "wdt", directory / "fallback"
        # Every temporary path is generated by tempfile, with no shell metacharacters.
        wdt.write_text(f'#!/bin/sh\necho "wdt $*" >> "{self.events}"\n'
                       + ('[ "$1" != disable ]\n' if wdt_fail else "exit 0\n"))
        fallback.write_text(f'#!/bin/sh\necho fallback >> "{self.events}"\n')
        wdt.chmod(0o700)
        fallback.chmod(0o700)
        self.command = [str(BUILD / "oa-supervise"), "--heartbeat", str(self.hb),
                        "--ready", str(self.ready), "--wdt", str(wdt), "--fallback", str(fallback),
                        "--fail", str(self.fail), "--enable", str(self.enable), "--safe", str(self.safe),
                        "--startup-ms", "800", "--timeout-ms", "1500", "--stable-ms", "300",
                        "--", str(BUILD / "openaurora"), "--sock", "", "--config", str(self.config)]
        if modules:
            self.command += ["--modules", str(BUILD / "modules"),
                             "--load", str(BUILD / "tests/mod_recovery_fixture.so"),
                             "--load", "ui_engine", "--load", "ui_vendor"]
        self.logfile = (directory / "log").open("w")
        self.process = None

    def start(self):
        self.process = subprocess.Popen(self.command, stdin=subprocess.DEVNULL,
                                        stdout=self.logfile, stderr=self.logfile)

    def pid(self):
        return int(until(lambda: read(self.hb)).split()[0])

    def fallback(self):
        assert self.process.wait(timeout=5) == 0
        assert read(self.events).splitlines()[-2:] == ["wdt set 10", "fallback"], read(self.events)

    def close(self):
        if self.process and self.process.poll() is None:
            self.process.terminate()
            try:
                self.process.wait(timeout=5)
            except subprocess.TimeoutExpired:
                self.process.kill()
                self.process.wait()
        self.logfile.close()


def case(name, action, **kw):
    with tempfile.TemporaryDirectory(prefix="oa-recovery-") as tmp:
        run = Run(Path(tmp), **kw)
        try:
            action(run)
            print("  ok  ", name)
        except Exception:
            print(read(run.dir / "log"))
            raise
        finally:
            run.close()


def healthy(r):
    r.start()
    pid = r.pid()
    until(lambda: read(r.ready))
    first = read(r.hb)
    until(lambda: read(r.hb) != first)
    assert r.process.poll() is None
    until(lambda: read(r.fail) == "0\n")
    os.kill(pid, signal.SIGTERM)
    r.fallback()


def blocked_callback(r):
    r.start()
    r.pid()
    until(lambda: "stable;" in read(r.dir / "log"))
    r.stall.touch()
    r.fallback()
    assert "heartbeat missing" in read(r.dir / "log")


def stopped(r):
    r.start()
    pid = r.pid()
    until(lambda: read(r.ready))
    os.kill(pid, signal.SIGSTOP)
    r.fallback()
    assert not Path(f"/proc/{pid}").exists(), "stopped child must be reaped before fallback"


def startup(r):
    r.start()
    r.fallback()
    assert "startup deadline" in read(r.dir / "log")


def failed_present(r):
    r.start()
    r.fallback()
    assert "portal present failed" in read(r.dir / "log")
    assert "first present acknowledged" not in read(r.dir / "log")


def stale_ready(r):
    r.hb.write_text("1 999999999999\n")
    r.ready.write_text("1 1920x1080\n")
    r.start()
    r.fallback()
    assert "first present acknowledged" not in read(r.dir / "log")


def failures(r):
    for _ in range(3):
        r.start()
        r.fallback()
    assert read(r.fail) == "3\n"
    assert not r.enable.exists()


def safe(r):
    r.safe.touch()
    r.start()
    assert r.process.wait(timeout=5) == 0
    assert read(r.events) == "fallback\n"
    assert not r.fail.exists()


def safe_running(r):
    r.start()
    r.pid()
    r.safe.touch()
    r.fallback()


def watchdog_failure(r):
    r.start()
    r.fallback()
    assert not r.hb.exists()
    assert "watchdog disable failed" in read(r.dir / "log")


def idle_signal(r):
    # No module timers: heartbeat still wakes an otherwise idle poll().
    child = subprocess.Popen(r.command[r.command.index("--") + 1:], stdin=subprocess.DEVNULL,
                             stdout=r.logfile, stderr=r.logfile)
    try:
        until(lambda: read(r.hb))
        first = read(r.hb)
        until(lambda: read(r.hb) != first)
        child.terminate()
        assert child.wait(timeout=2) == 0
        assert not r.hb.exists()
    finally:
        if child.poll() is None:
            child.kill()
            child.wait()


def suite_reload(r):
    # A child that exits 75 asks oa-supervise to relaunch it. The second run
    # exits 0, which is a real stop, so the vendor fallback follows. The
    # watchdog must stay disabled between the two runs.
    counter, child = r.dir / "child-count", r.dir / "child"
    child.write_text(
        "#!/bin/sh\n"
        f'n=$(cat "{counter}" 2>/dev/null || echo 0)\n'
        'n=$((n+1))\n'
        f'echo "$n" > "{counter}"\n'
        f'echo "child$n" >> "{r.events}"\n'
        '[ "$n" -eq 1 ] && exit 75\n'
        "exit 0\n")
    child.chmod(0o700)
    r.command = [str(BUILD / "oa-supervise"), "--heartbeat", str(r.hb),
                 "--ready", str(r.ready), "--wdt", str(r.dir / "wdt"),
                 "--fallback", str(r.dir / "fallback"), "--fail", str(r.fail),
                 "--enable", str(r.enable), "--safe", str(r.safe),
                 "--startup-ms", "800", "--timeout-ms", "1500",
                 "--stable-ms", "300", "--", str(child)]
    r.start()
    r.fallback()
    events = read(r.events).splitlines()
    assert events == ["wdt disable", "child1", "child2", "wdt set 10", "fallback"], events
    assert read(counter).strip() == "2"
    assert "suite reload requested" in read(r.dir / "log")
    assert read(r.fail) == "1\n"


if __name__ == "__main__":
    case("heartbeat advances; SIGTERM exits; fallback re-arms watchdog", healthy)
    case("blocked module callback stops heartbeat and triggers fallback", blocked_callback)
    case("SIGSTOPped child is killed and reaped", stopped)
    case("blocking module startup has a deadline", startup, extra="test.start_stall = 1\n")
    case("failed present never acknowledges readiness", failed_present, extra="test.present_fail = 1\n")
    case("old receipts cannot keep a new process alive", stale_ready, modules=False)
    case("three failures remove the opt-in marker", failures, extra="test.start_stall = 1\n")
    case("safe marker bypasses takeover", safe)
    case("safe marker during takeover returns to vendor UI", safe_running)
    case("failed watchdog disable skips child and falls back", watchdog_failure, wdt_fail=True)
    case("idle event loop heartbeats and exits on SIGTERM", idle_signal, modules=False)
    case("suite reload restarts without re-arming the watchdog", suite_reload, modules=False)
